"""`kubesage gitops`: commit a run to a GitOps repo as a kustomize overlay on a new branch, optionally push it
and open a pull request. The repo is left on the branch it was on."""
from __future__ import annotations

import os
import subprocess
from dataclasses import dataclass
from pathlib import Path

import yaml

from kubesage import summary
from kubesage.pipeline import AnalysisResult
from kubesage.recommend.render import deployment_patch

MANAGED_SUFFIXES = (".patch.yaml", ".migrate.yaml", ".keda.yaml")
MANAGED_FILES = ("kustomization.yaml", "REPORT.md")


class GitOpsError(RuntimeError):
    pass


@dataclass
class Exported:
    branch: str
    commit: str
    files: list[str]
    pushed: bool
    pr_url: str | None = None


GIT_TIMEOUT = 120  # a hung push or credential prompt must not hold the server's operation lock forever


def _run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=GIT_TIMEOUT,
                              env={**os.environ, "GIT_TERMINAL_PROMPT": "0"}, **kw)
    except subprocess.TimeoutExpired as exc:
        raise GitOpsError(f"{' '.join(cmd[:4])}: no answer after {GIT_TIMEOUT} s") from exc
    except OSError as exc:
        raise GitOpsError(f"{cmd[0]}: {exc}") from exc


def _git(repo: Path, *args: str) -> str:
    proc = _run(["git", "-C", str(repo), *args])
    if proc.returncode:
        raise GitOpsError(f"git {' '.join(args)}: {proc.stderr.strip() or proc.stdout.strip()}")
    return proc.stdout.strip()


def overlay(run_dir: Path, kustomize_base: str) -> dict[str, str]:
    """The overlay's files: the run's patches and ScaledObjects plus a kustomization.yaml over `kustomize_base`."""
    files = {f.name: f.read_text() for f in sorted((run_dir / "manifests").iterdir()) if f.name.endswith(MANAGED_SUFFIXES)}
    # Once a ScaledObject owns the replica count, Git must stop pinning spec.replicas, or the GitOps controller
    # and the HPA fight over it. In a strategic-merge patch, null deletes the field.
    for keda in [n for n in files if n.endswith(".keda.yaml")]:
        so = yaml.safe_load(files[keda])
        name, namespace = so["spec"]["scaleTargetRef"]["name"], so["metadata"]["namespace"]
        patch = f"{name}.patch.yaml"
        doc = yaml.safe_load(files[patch]) if patch in files else deployment_patch(namespace, name, {})
        doc["spec"]["replicas"] = None
        files[patch] = yaml.safe_dump(doc, sort_keys=False)
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
        "resources": [kustomize_base, *sorted(n for n in files if n.endswith(".keda.yaml"))],
        "patches": [{"path": n} for n in sorted(files) if n.endswith((".patch.yaml", ".migrate.yaml"))],
    }
    files["kustomization.yaml"] = (f"# Generated by KubeSage from run {run_dir.name}. Regenerate it; don't edit.\n"
                                   + yaml.safe_dump(kustomization, sort_keys=False))
    return files


def export(run_dir: Path, repo: Path, *, path: str, kustomize_base: str, branch: str | None = None,
           base_branch: str | None = None, remote: str = "origin", push: bool = False,
           open_pr: bool = False) -> Exported:
    repo = Path(repo).resolve()
    if _git(repo, "status", "--porcelain"):
        raise GitOpsError(f"{repo} has uncommitted changes; commit or stash them first")
    report = AnalysisResult.model_validate_json((run_dir / "report.json").read_text())
    original = _git(repo, "rev-parse", "--abbrev-ref", "HEAD")
    base_branch = base_branch or original
    branch = branch or f"kubesage/rightsize-{run_dir.name}"
    files = overlay(run_dir, kustomize_base)
    files["REPORT.md"] = body = summary.markdown(report)
    title = summary.title(report)

    _git(repo, "switch", "-c", branch, base_branch)
    try:
        target = repo / path
        target.mkdir(parents=True, exist_ok=True)
        for old in target.iterdir():  # the overlay directory belongs to KubeSage; drop the previous run's files
            if old.name.endswith(MANAGED_SUFFIXES) or old.name in MANAGED_FILES:
                old.unlink()
        for name, text in files.items():
            (target / name).write_text(text)
        _git(repo, "add", "-A", "--", path)
        _git(repo, "commit", "-m", title, "-m", f"Generated by KubeSage from run {run_dir.name}; see {path}/REPORT.md.")
        commit = _git(repo, "rev-parse", "HEAD")
        if push or open_pr:
            _git(repo, "push", "-u", remote, branch)
    finally:
        _git(repo, "switch", original)

    pr_url = None
    if open_pr:
        proc = _run(["gh", "pr", "create", "--base", base_branch, "--head", branch, "--title", title, "--body", body],
                    cwd=repo)
        if proc.returncode:
            raise GitOpsError(f"branch {branch} pushed, but gh pr create failed: {proc.stderr.strip()}")
        pr_url = proc.stdout.strip().splitlines()[-1]
    return Exported(branch=branch, commit=commit, files=sorted(files), pushed=push or open_pr, pr_url=pr_url)
