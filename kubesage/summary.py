"""Markdown summary of an analysis run, used as the GitOps PR body and REPORT.md."""
from __future__ import annotations

from kubesage.pipeline import AnalysisResult


def _usd(v: float) -> str:
    return f"${v:,.4f}" if abs(v) < 1 else f"${v:,.2f}"


def savings(r: AnalysisResult) -> tuple[float, float]:
    """(allocation-view monthly savings, node-pool monthly savings)."""
    alloc = sum(w.monthly_before_usd - w.monthly_after_usd for w in r.workloads)
    pool = r.node_pool.before_monthly_usd - r.node_pool.after_monthly_usd if r.node_pool else 0.0
    return alloc, pool


def title(r: AnalysisResult) -> str:
    alloc, pool = savings(r)
    return f"kubesage: right-size {r.namespace} (~{_usd(max(alloc, pool))}/mo)"


def markdown(r: AnalysisResult) -> str:
    alloc, pool = savings(r)
    models = {e.workload: e.model for e in r.ledger if e.stage == "recommend"}
    lines = [f"## KubeSage right-sizing for `{r.namespace}` ({r.window_days}-day window)", ""]
    if r.mode == "mock":
        lines += ["> **Mock mode:** recommendations came from KubeSage's deterministic stand-ins, not an LLM, "
                  "and token costs are estimates.", ""]
    before = sum(w.monthly_before_usd for w in r.workloads)
    lines += ["| | before | after | saves |", "|---|---|---|---|",
              f"| Requested capacity (allocation view) | {_usd(before)}/mo | {_usd(before - alloc)}/mo | {_usd(alloc)}/mo |"]
    if r.node_pool:
        n = r.node_pool
        lines.append(f"| Node pool (billing view) | {n.before_nodes}× {n.before_sku} {_usd(n.before_monthly_usd)}/mo | "
                     f"{n.choice.nodes}× {n.choice.sku} {_usd(n.after_monthly_usd)}/mo | {_usd(pool)}/mo |")
    lines += ["", f"LLM cost of this analysis: **{_usd(r.llm_cost_usd)}**. The same calls all on the strategist tier "
                  f"would cost {_usd(r.baselines_usd['all_calls_on_strategist'])}.", "",
              "### Workloads", "", "| workload | triage | model | $/mo before → after | risk |", "|---|---|---|---|---|"]
    for w in r.workloads:
        rec = w.recommendation
        lines.append(f"| `{w.id}` | {w.triage.status} | {models.get(w.id, '—')} | "
                     f"{_usd(w.monthly_before_usd)} → {_usd(w.monthly_after_usd)} | {rec.risk if rec else '—'} |")
    for w in r.workloads:
        if not w.recommendation:
            continue
        lines += ["", f"#### `{w.id}`", "", w.recommendation.diagnosis]
        lines += [f"- guardrail: {n}" for n in w.guardrail_notes]
        lines += [f"- follow-up: {f}" for f in w.recommendation.follow_ups]
        if w.manifests:
            lines.append("- files: " + ", ".join(f"`{name}`" for name in w.manifests))
    if r.node_pool:
        lines += ["", "#### Node pool", "", r.node_pool.choice.rationale]
        # The burst warning and any change to the model's pick are part of the evidence; never drop them.
        lines += [f"- note: {n}" for n in r.node_pool.notes]
        if r.node_pool.migrations:
            lines.append(f"- `*.migrate.yaml` pins every workload to `{r.node_pool.node_label}={r.node_pool.choice.sku}`. "
                         "Provision that node pool before merging.")
    if r.notes:
        lines += ["", "#### Pipeline notes", ""] + [f"- {n}" for n in r.notes]
    lines += ["", "---", f"Generated by KubeSage at {r.generated_at}."]
    return "\n".join(lines) + "\n"
